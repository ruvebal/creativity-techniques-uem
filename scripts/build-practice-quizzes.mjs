#!/usr/bin/env node
/**
 * Public practice quizzes (PHASE-EX10 deliverable 2).
 *
 *   node scripts/build-practice-quizzes.mjs [--check]
 *
 * Reads the PRIVATE knowledge-test bank (creativity-techniques-pedagogy/excellence/
 * assessment/, never published) and writes one public page per unit,
 * docs/practice/en/<unit slug>/index.html, with the five questions marked
 * `public_quiz: true`. Each question sits in an element with `data-question`; the answer
 * is revealed on click (<details>, no JavaScript) with a link to the lesson block that
 * holds it and the author-date of the verified work it rests on. Only stem, options,
 * answer and the lesson pointer are published: no RA codes, Bloom levels, drafting notes
 * or the rest of the bank. Also writes docs/practice/en/index.html.
 *
 * --check: exit 1 if a committed page differs from what this script would write.
 * Wired into `npm run prebuild`. Tests: scripts/tests/practice-quizzes.test.mjs.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';
import yaml from 'js-yaml';

import { authorDate, escapeHtml } from './build-method-cards.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
export const BANK = join(root, 'creativity-techniques-pedagogy/excellence/assessment/question-bank.yml');
export const PER_UNIT = 5;
const LETTERS = 'ABCDEFGH';

/**
 * Options for an mcq: answer + distractors. The answer's position rotates with `slot`
 * (the k-th mcq on the page, plus a per-unit offset from the unit hash), so the letters
 * stay balanced on every page and stable across builds.
 */
export function options(q, slot = 0) {
  const wrong = (q.distractors || []).map(String);
  const offset = parseInt(createHash('sha256').update(String(q.unit)).digest('hex').slice(0, 8), 16);
  const at = (slot + offset) % (wrong.length + 1);
  const all = [...wrong];
  all.splice(at, 0, String(q.answer));
  return { all, correct: at };
}

function lessonTitle(slug) {
  const md = readFileSync(join(root, `docs/lessons/en/creativity-techniques/${slug}/index.md`), 'utf8');
  return (md.match(/^title:\s*['"]?(.*?)['"]?\s*$/m) || [])[1] || slug;
}

export function questionHtml(q, n, { lesson, references, slot = 0 }) {
  const cite = references[q.ref] ? authorDate(references[q.ref].chicago) : null;
  const opts = q.type === 'mcq' ? options(q, slot) : null;
  const body = opts
    ? `<ol class="practice-quiz__options" type="A">${opts.all.map((o) => `<li>${escapeHtml(o)}</li>`).join('')}</ol>`
    : `<p class="practice-quiz__hint">${q.type === 'case' ? 'Apply the lesson to this situation in two or three sentences, then compare.' : 'Answer in one or two sentences, then compare.'}</p>`;
  const answer = opts ? `(${LETTERS[opts.correct]}) ${escapeHtml(q.answer)}` : escapeHtml(q.answer);
  return [
    `<article class="practice-quiz__question" id="q${n}" data-question="${escapeHtml(q.id)}">`,
    `<p class="practice-quiz__stem"><strong>${n}.</strong> ${escapeHtml(q.stem)}</p>`,
    body,
    '<details>',
    '<summary>Show answer</summary>',
    `<p><strong>Answer:</strong> ${answer}</p>`,
    `<p class="practice-quiz__check">Check it in the lesson: <a href="{{ '${lesson}' | relative_url }}#${escapeHtml(q.anchor)}">${escapeHtml(q.where)}</a>${cite ? ` · <a href="#ref-${escapeHtml(q.ref)}">(${escapeHtml(cite)})</a>` : ''}</p>`,
    '</details>',
    '</article>',
  ].join('\n');
}

export function quizPage(unit, info, questions, { references, title }) {
  const refs = [...new Set(questions.map((q) => q.ref))].sort();
  const fm = [
    '---',
    'layout: default',
    `title: "${unit} practice quiz"`,
    'lang: en',
    `permalink: /practice/en/${info.slug}/`,
    `description: "Five practice questions on ${unit} with answers you open on click. Practice only: not graded, nothing recorded."`,
    `references: [${refs.join(', ')}]`,
    '---',
    '',
  ].join('\n');
  return `${fm}{% comment %}Generated by scripts/build-practice-quizzes.mjs (npm run prebuild). Do not edit by hand.{% endcomment %}
<div class="practice-quiz">
<h1>${escapeHtml(unit)} practice quiz</h1>
<p>Five questions on <a href="{{ '${info.lesson}' | relative_url }}">${escapeHtml(title)}</a>. Answer each one from memory first, then open the answer and check the lesson. Trying to recall before you look is the point of the exercise.</p>
<p>This page is practice only: it is not graded, it is not the exam, and nothing you do here is recorded.</p>
${questions.map((q, i) => questionHtml(q, i + 1, { lesson: info.lesson, references, slot: questions.slice(0, i).filter((x) => x.type === 'mcq').length })).join('\n')}
<section class="practice-quiz__references" id="references">
<h2>References</h2>
{% include references.html %}
</section>
<p>More practice: <a href="{{ '/practice/en/' | relative_url }}">all practice quizzes</a>.</p>
</div>
`;
}

export function indexPage(units) {
  return `---
layout: default
title: "Practice quizzes"
lang: en
permalink: /practice/en/
description: "Practice quizzes for each unit (answers on click) and the printable peer rating sheet."
---
{% comment %}Generated by scripts/build-practice-quizzes.mjs (npm run prebuild). Do not edit by hand.{% endcomment %}
<div class="practice-quiz">
<h1>Practice quizzes</h1>
<p>Five questions per unit, answers on click. Practice only: not graded and nothing is recorded. The knowledge tests carry most of the course grade (see <a href="{{ '/evaluation/' | relative_url }}">Evaluation</a>); recalling before you look is a good way to prepare.</p>
<ul>
${Object.entries(units).map(([u, info]) => `<li><a href="{{ '/practice/en/${info.slug}/' | relative_url }}">${escapeHtml(u)} practice quiz</a></li>`).join('\n')}
</ul>
<p>Classroom tool: the printable <a href="{{ '/practice/en/peer-rating-sheet/' | relative_url }}">peer rating sheet</a>.</p>
</div>
`;
}

export function buildPages(bank, references, titles = {}) {
  const pages = {};
  for (const [unit, info] of Object.entries(bank.units || {})) {
    const qs = (bank.questions || []).filter((q) => q.unit === unit && q.public_quiz);
    if (qs.length !== PER_UNIT) throw new Error(`${unit}: ${qs.length} public_quiz questions (need ${PER_UNIT})`);
    pages[`docs/practice/en/${info.slug}/index.html`] = quizPage(unit, info, qs, { references, title: titles[unit] || unit });
  }
  pages['docs/practice/en/index.html'] = indexPage(bank.units || {});
  return pages;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (!existsSync(BANK)) {
    console.warn(`build-practice-quizzes: private bank missing (${relative(root, BANK)}); committed pages kept`);
    process.exit(0);
  }
  const bank = yaml.load(readFileSync(BANK, 'utf8'));
  const references = yaml.load(readFileSync(join(root, 'docs/_data/references.yml'), 'utf8'));
  const titles = Object.fromEntries(Object.entries(bank.units).map(([u, info]) => [u, lessonTitle(info.slug)]));
  const pages = buildPages(bank, references, titles);
  let stale = 0;
  for (const [rel, html] of Object.entries(pages)) {
    const path = join(root, rel);
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current === html) continue;
    if (process.argv.includes('--check')) { stale += 1; console.error(`stale: ${rel}`); continue; }
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, html, 'utf8');
  }
  console.log(`build-practice-quizzes: ${Object.keys(pages).length} page(s)${process.argv.includes('--check') ? `, ${stale} stale` : ''}`);
  process.exit(stale ? 1 : 0);
}
